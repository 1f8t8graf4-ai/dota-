#!/bin/bash
# 25.10: старая склейка прыгала на шве (после хвоста шёл кадр 0, а хвост кончался на кадре «хвост»).
# Теперь всё делает tools/hero_loop.py (сам ищет начало и конец петли, проверяет шов). Аргументы «тело» больше не нужны.
# Использование: ./hero_loop.sh IN.mp4 OUT.mp4 [-- любые флаги hero_loop.py, напр. --fade 0.6 --map]
IN="${1:?нет входного файла}"; OUT="${2:?нет выходного файла}"; shift 2
[ "$1" = "--" ] && shift
exec python3 "$(dirname "$0")/hero_loop.py" "$IN" "$OUT" "$@"
