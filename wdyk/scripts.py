#   3–6 «доказательств» → поворот к зрителю → ссылка на следующую серию.
# Отличие: «доказательства» — НАСТОЯЩИЕ факты (источники ниже), абсурдный только вывод. Про реальных людей —
#   только безобидная шутка (никаких обвинений), в описании ролика — «parody / satire».
# Разметка (как в NightFabel): {ПОКАЗ|как говорить}; *слово — жёлтым; !слово — красным.
