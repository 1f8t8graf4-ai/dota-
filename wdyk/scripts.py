import re


def parse(s):
    """→ (spoken_text, [ {d: показ, sp: [озвученные слова], c: ''|'y'|'r'} ])"""
    out, spoken = [], []
    for m in re.finditer(r'\{([^|}]*)\|([^}]*)\}([.,?!…]*)|(\S+)', s):
        if m.group(4) is not None:
            w = m.group(4)
            c = ''
            lead = ''
            # «'subscribe'...» — кавычка перед звёздочкой
            if w[:1] in "'\"“" and len(w) > 1 and w[1] in '*!':
                lead, w = w[0], w[1:]
            if w.startswith('*'):
                c, w = 'y', w[1:]
            elif w.startswith('!'):
                c, w = 'r', w[1:]
            w = lead + w
            if w in ('—', '–'):
                spoken.append(w)
                continue
            out.append({'d': w, 'sp': [w], 'c': c})
            spoken.append(w)
        else:
            d, sp, pu = m.group(1), m.group(2).split(), m.group(3)
            sp[-1] += pu
            out.append({'d': d + pu, 'sp': sp, 'c': 'y'})
            spoken += sp
    text = ' '.join(spoken)
    text = re.sub(r'\s+([.,?!])', r'\1', text)
    return text, out


