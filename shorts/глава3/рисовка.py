def mark_voice(b):
    hits = {norm(w) for w, _, _ in b['sh'] if w}
    out, last = [], 0
    for m in re.finditer(WRE, b['text']):
        out.append(E(b['text'][last:m.start()]))
        w = m.group(0)
        out.append(f'<mark>{E(w)}</mark>' if norm(w) in hits else E(w)); last = m.end()
    out.append(E(b['text'][last:]))
    return ''.join(out)

