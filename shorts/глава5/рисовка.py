def find(W, anc):
    w, n = anc if isinstance(anc, tuple) else (anc, 1)
    hits = [j for j, x in enumerate(W) if norm(x).startswith(norm(w))]
    assert len(hits) >= n, (anc, W)
    return hits[n - 1]

