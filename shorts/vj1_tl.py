#!/usr/bin/env python3
"""Промо «Представь, ты…» про «Джул» (16.11): черновой таймлайн без голоса — темп 2,5 слова/с.
Слова идут с расчётным временем; когда будет голос, этот файл заменяется словами из распознавания (el13.py), картинка подстроится сама.
  python3 vj1_tl.py → tl/vj1s-ru.json"""
import json, os, re
PH = [
    'Представь, ты студент Стэнфорда. Куришь и хочешь бросить.',
    'Ты ещё не знаешь, что станешь миллиардером.',
    'Вы с другом решаете убить обычную сигарету.',
    'Ты роешься в старых архивах табачных компаний.',
    'И находишь патент семьдесят девятого года.',
    'Добавь к никотину кислоту — и он становится солью.',
    'Пар мягкий, горло не дерёт, никотин бьёт сильнее.',
    'В две тысячи пятнадцатом ты выпускаешь «Джул».',
    'Он похож на флешку и заряжается от ноутбука.',
    'Вкусы — манго, крем-брюле, мята.',
    'В одном картридже — никотин целой пачки.',
    'Реклама с молодыми моделями — прямо на Таймс-сквер.',
    'Через три года у тебя три четверти рынка Америки.',
    'Декабрь восемнадцатого. Звонят хозяева «Мальборо».',
    'Двенадцать и восемь десятых миллиарда за треть компании.',
    'Твоя флешка стоит тридцать восемь миллиардов.',
    'Только власти уже называют это эпидемией.',
    'Через год электронки парят пять миллионов школьников.',
    'Вкусы запрещают. Директор уходит. Исков — тысячи.',
    'Власти приказывают убрать «Джул» с рынка.',
    'Доля за двенадцать миллиардов теперь стоит меньше полумиллиарда.',
    'А твоё место за год занимают китайские одноразки.',
    'Только соль придумал не ты.',
    'И этот патент — лишь первая улика.',
    'Всё дело — в фильме «Что вы знаете о никотине?»',
]
TAIL = 2.6   # после последнего слова: доска и кнопка
words, t = [], .3
for i, s in enumerate(PH):
    toks = [w for w in s.split() if w != '—']
    sw = []
    for j, w in enumerate(toks):
        n = len(re.sub(r'[^\wё-]', '', w.lower()))
        d = .09 + .062 * n
        sw.append({'d': w, 'a': round(t, 3), 'b': round(t + d, 3)})
        t += d + .05
        if re.search(r'[.?!]»?$', w) and j < len(toks) - 1: t += .28
        elif re.search(r'[,:]$', w): t += .12
    if i + 1 < len(PH) and '—' in s.split()[1:2]: pass
    words.append({'i': i, 'a': sw[0]['a'], 'b': sw[-1]['b'], 'text': s, 'words': sw})
    t += .34
n = sum(len(s['words']) for s in words)
k = (n / 2.45) / (words[-1]['b'] - .3)   # темп 2,45 слова/с, как у Макса
for s in words:
    for w in s['words']: w['a'] = round(.3 + (w['a'] - .3) * k, 3); w['b'] = round(.3 + (w['b'] - .3) * k, 3)
    s['a'], s['b'] = s['words'][0]['a'], s['words'][-1]['b']
dur = round(words[-1]['b'] + TAIL, 2)
json.dump({'ep': 'vj1s-ru', 'lang': 'ru', 'dur': dur, 'fps': 30, 'voice': 'draft', 'sent': words, 'b0': words[-1]['b'], 'endT': dur - .1}, open(os.path.join(os.path.dirname(__file__), 'tl', 'vj1s-ru.json'), 'w'), ensure_ascii=False)
print('слов', n, 'длина', dur, 'с, темп', round(n / words[-1]['b'], 2), 'слова/с')
